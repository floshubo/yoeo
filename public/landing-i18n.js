const validLanguages = new Set(Object.keys(siteCopy));
const queryLanguage = new URLSearchParams(window.location.search).get("lang");
let savedLanguage;
try { savedLanguage = window.localStorage.getItem("yoeo-site-lang"); } catch {}
const browserLanguage = window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : window.navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
let currentLanguage = validLanguages.has(queryLanguage) ? queryLanguage : validLanguages.has(savedLanguage) ? savedLanguage : browserLanguage;
const languageNames = { en: "English", de: "Deutsch", zh: "中文" };
const languageCodes = { en: "EN", de: "DE", zh: "中文" };

function translate(key) { return siteCopy[currentLanguage]?.[key] || siteCopy.en[key] || key; }
window.yoeoSiteT = translate;

function applyLanguage(language, updateUrl = false) {
  currentLanguage = language;
  const page = document.body.dataset.page;
  document.documentElement.lang = page === "privacy" ? "en" : language === "zh" ? "zh-Hans" : language;
  document.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = translate(element.dataset.i18n); });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => { element.alt = translate(element.dataset.i18nAlt); });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => { element.setAttribute("aria-label", translate(element.dataset.i18nAria)); });
  document.querySelectorAll("[data-lang]").forEach((button) => { button.setAttribute("aria-pressed", String(button.dataset.lang === language)); });
  const languageTrigger = document.querySelector(".language-trigger");
  if (languageTrigger) languageTrigger.setAttribute("aria-label", `${translate("languageLabel")}: ${languageNames[language]}`);
  document.querySelectorAll("[data-current-language]").forEach((element) => { element.textContent = languageCodes[language]; });
  document.querySelectorAll(".language-menu").forEach((element) => { element.lang = language === "zh" ? "zh-Hans" : language; });
  document.querySelectorAll("[data-site-link]").forEach((link) => {
    const url = new URL(link.getAttribute("href"), window.location.origin);
    if (language === "en") url.searchParams.delete("lang"); else url.searchParams.set("lang", language);
    link.href = url.pathname + url.search + url.hash;
  });
  const policyNote = document.querySelector(".translation-note");
  if (policyNote) {
    policyNote.hidden = language === "en";
    policyNote.lang = language === "zh" ? "zh-Hans" : language;
  }
  document.title = page === "privacy" ? "Privacy Policy — YOEO" : page === "support" ? translate("supportTitle") : translate("pageTitle");
  const description = document.querySelector('meta[name="description"]');
  if (description && page === "landing") description.content = translate("pageDescription");
  if (updateUrl) {
    try { window.localStorage.setItem("yoeo-site-lang", language); } catch {}
    const url = new URL(window.location.href);
    if (language === "en") url.searchParams.delete("lang"); else url.searchParams.set("lang", language);
    window.history.replaceState(null, "", url.pathname + url.search + url.hash);
  }
  window.dispatchEvent(new CustomEvent("yoeo:languagechange", { detail: { language } }));
}

const languageMenu = document.querySelector(".language-menu");
const languageTrigger = languageMenu?.querySelector(".language-trigger");
const languageOptions = languageMenu?.querySelector(".language-options");
function closeLanguageMenu() {
  if (!languageOptions || !languageTrigger) return;
  languageOptions.hidden = true;
  languageTrigger.setAttribute("aria-expanded", "false");
}
languageTrigger?.addEventListener("click", () => {
  languageOptions.hidden = !languageOptions.hidden;
  languageTrigger.setAttribute("aria-expanded", String(!languageOptions.hidden));
});
document.addEventListener("pointerdown", (event) => {
  if (languageMenu && !languageMenu.contains(event.target)) closeLanguageMenu();
});
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && languageOptions && !languageOptions.hidden) {
    closeLanguageMenu();
    languageTrigger.focus();
  }
});
document.querySelectorAll("[data-lang]").forEach((button) => button.addEventListener("click", () => {
  applyLanguage(button.dataset.lang, true);
  closeLanguageMenu();
  languageTrigger?.focus();
}));
applyLanguage(currentLanguage);
